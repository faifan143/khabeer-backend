// Extract all state values for database validation
export const DB_STATES = OMAN_STATES.flatMap(governorate =>
    governorate.states.map(state => state.value)
);

// Helper functions
export const isValidState = (state: string): boolean => {
    return DB_STATES.includes(state as any);
};

// Get all states as a flat array for simple dropdowns
export const getAllStates = () => {
    return OMAN_STATES.flatMap(governorate =>
        governorate.states.map(state => ({
            value: state.value,
            label: state.label
        }))
    );
};

// Get states by governorate
export const getStatesByGovernorate = (governorateEn: string) => {
    return OMAN_STATES.find(g => g.governorate.en === governorateEn)?.states || [];
};

// Get governorate by state
export const getGovernorateByState = (stateValue: string) => {
    return OMAN_STATES.find(governorate =>
        governorate.states.some(state => state.value === stateValue)
    )?.governorate;
};

